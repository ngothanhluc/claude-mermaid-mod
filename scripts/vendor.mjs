// Hooks modules cannot resolve bare specifiers, so lovely-mermaid ships as one
// self-contained ESM file the hooks import by relative path.
import { build } from 'esbuild'
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs'

const { version } = JSON.parse(readFileSync('node_modules/lovely-mermaid/package.json', 'utf8'))
if (version !== '0.3.3') throw new Error(`lovely-mermaid ${version} installed, expected 0.3.3`)

await build({
  stdin: { contents: "export { render } from 'lovely-mermaid'", resolveDir: '.' },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile: 'hooks/vendor/lovely-mermaid.js',
  legalComments: 'none',
  banner: { js: `// Generated by scripts/vendor.mjs from lovely-mermaid ${version} (Apache-2.0, see LICENSE-lovely-mermaid). Do not edit.` },
})
copyFileSync('node_modules/lovely-mermaid/LICENSE', 'hooks/vendor/LICENSE-lovely-mermaid')
writeFileSync(
  'hooks/vendor/lovely-mermaid.d.ts',
  readFileSync('node_modules/lovely-mermaid/dist/types.d.ts', 'utf8').replace(/\/\/# sourceMappingURL.*\n?/, '') +
    'export declare function render(src: string): MermaidArt | null;\n',
)
